const HISTORY_RANGE_MS: Record<PerformanceHistoryRange, number> = {
  "24h": 24 * 60 * 60 * 1000,
  "7d": 7 * 24 * 60 * 60 * 1000,
  "30d": 30 * 24 * 60 * 60 * 1000,
};

// Mirrors monitor/service.ts's own private verifyOwnership exactly — each
// module keeps its own tiny ownership check against websiteRepository rather
// than sharing a cross-module import, consistent with the existing pattern.
async function verifyOwnership(websiteId: string, userId: string) {
  const website = await websiteRepository.findById(websiteId, userId);

  if (!website) {
    throw new NotFoundError(`Website with id '${websiteId}' not found.`);
  }

  return website;
}

// Stage P1: curated, generic, user-safe messages — PageUrlValidationError's
// own .message is never forwarded verbatim (mirrors seo/service.ts's
// SAFE_FETCH_MESSAGES precedent). Every case here is a client input
// problem, never an upstream failure, so all map to the existing
// ValidationError (400) — no 502 tier is needed the way SEO's safeFetch
// mapping needs one for genuine upstream unreachability.
const PAGE_URL_MESSAGES: Record<PageUrlErrorCode, string> = {
  INVALID_URL: "The page URL could not be parsed. Provide a full URL, e.g. https://example.com/about/.",
  UNSUPPORTED_PROTOCOL: "The page URL's protocol is not supported — only http and https are allowed.",
  CREDENTIALS_NOT_ALLOWED: "The page URL must not contain credentials.",
  BLOCKED_DESTINATION: "This page URL resolves to a destination Sentinel AI does not allow.",
  HOSTNAME_MISMATCH: "The page URL must belong to this website.",
};

function mapPageUrlError(error: PageUrlValidationError): AppError {
  return new ValidationError(PAGE_URL_MESSAGES[error.code]);
}

// Shared by every endpoint below so "no page URL supplied -> Website.url"
// and "explicit page URL -> validated + same-hostname-enforced" behave
// identically everywhere (Stage P1 §5/§7/§14).
function resolveRequestedPageUrl(rawPageUrl: string | undefined, websiteUrl: string): string {
  try {
    return resolvePageUrl(rawPageUrl, websiteUrl);
  } catch (error) {
    if (error instanceof PageUrlValidationError) {
      throw mapPageUrlError(error);
    }
    throw error;
  }
}

// Stage 15.3: shared by both runCheck and runAutomaticCheck below so Alert
// generation is never duplicated per call site — mirrors seo/service.ts's
// persistSeoAlerts exactly, including its failure-handling philosophy: a
// Performance Alert is a side effect of a successful check, never a reason
// to fail one. Any unexpected write failure is caught and logged (never
// rethrown), so the caller always gets back the successfully persisted
// PerformanceCheck regardless of Alert-write outcome.
//
// NOT fully self-healing (verified, not assumed — Stage 15.3 §19): if this
// write fails for check B, and a later check C compares against B (not
// against the pre-B state), a genuinely-new-at-B rating transition that's
// still in effect at C reads as an unchanged rating from B→C's perspective
// (same rating on both sides), not a new transition — so the missed
// DEGRADED/RECOVERED alert for that transition is never regenerated by any
// later check. This is an accepted, narrow, explicitly-documented residual
// gap: the underlying PerformanceCheck/stats/ratings data is never lost or
// incorrect, only a derived notification-side-effect for that specific
// transition may be missing. Deliberately not solved with an outbox/retry
// system, per §19's own guidance not to over-engineer this.
async function persistPerformanceAlert(
  websiteId: string,
  userId: string,
  pageUrl: string,
  strategy: PerformanceStrategy,
  previousCheck: PerformanceCheck | null,
  createdCheck: PerformanceCheck
): Promise<void> {
  const previousRating = previousCheck ? ratePerformanceMetrics(previousCheck).coreWebVitals : null;
  const currentRating = ratePerformanceMetrics(createdCheck).coreWebVitals;

  const alert = derivePerformanceAlert(websiteId, createdCheck.id, pageUrl, strategy, previousRating, currentRating);
  if (!alert) return;

  try {
    await performanceRepository.createAlertWithNotification(alert, userId);
  } catch (error) {
    console.error(
      `Performance alert write failed for website ${websiteId}, check ${createdCheck.id} (${strategy}):`,
      error instanceof Error ? error.message : "Unknown error"
    );
  }
}

// Exported ONLY for Stage 16.5's own test script (confirming the
// transition-trigger wiring and failure isolation using manually-prepared
// check rows, without depending on a real PageSpeed call) -- mirrors Stage
// 16.2's identical "export only for testing" precedent
// (PERFORMANCE_AI_OUTPUT_JSON_SCHEMA, mapOpenAiError). Not part of this
// module's public service API; no other file imports it.
// Stage 16.5: automatic AI enrichment -- a SIBLING of persistPerformanceAlert
// above, not a dependency of it (Stage 16.5 §22: AI must never determine
// whether an Alert exists). Both are independent consumers of the exact
// same previousRating/currentRating coreWebVitals comparison; this one
// additionally asks "did this transition newly ENTER a degraded tier"
// (performance/degradation.ts, which shares alerts.ts's own RATING_ORDER
// rather than redefining degradation).
//
// Called ONLY from runAutomaticCheck below, never from runCheck (manual
// Performance test) -- a manually-triggered Performance test must never
// itself cause automatic AI; only the scheduler's own background checks
// do (Stage 16.5 §13).
//
// AI is optional enrichment, monitoring is authoritative (Stage 16.5 §8):
// this function never throws -- any failure (configuration/timeout/
// provider-unavailable/invalid-response) is already persisted as a FAILED/
// INVALID_RESPONSE AiAnalysis row by aiAnalysisService's own shared
// pipeline, then surfaces here only as a rethrown AiAnalysisError, which
// is caught and logged, never allowed to abort the scheduler cycle, skip
// subsequent websites, or affect the just-committed PerformanceCheck/Alert
// in any way.
export async function maybeRunAutomaticAiAnalysis(
  previousCheck: PerformanceCheck | null,
  createdCheck: PerformanceCheck
): Promise<void> {
  const previousRating = previousCheck ? ratePerformanceMetrics(previousCheck).coreWebVitals : null;
  const currentRating = ratePerformanceMetrics(createdCheck).coreWebVitals;

  const transition = derivePerformanceDegradationTransition(previousRating, currentRating);
  if (!transition.enteredDegraded) return;

  try {
    // previousCheck here was fetched BEFORE createdCheck existed (same
    // call site as persistPerformanceAlert's own predecessor fetch above),
    // so it is already exactly createdCheck's true immediate same-(page,
    // strategy) predecessor -- no second predecessor lookup is needed.
    await aiAnalysisService.analyzePerformanceCheckInternal(createdCheck, previousCheck);
  } catch (error) {
    console.error(
      `Automatic AI analysis failed for website ${createdCheck.websiteId}, check ${createdCheck.id} (${createdCheck.strategy}):`,
      error instanceof Error ? error.message : "Unknown error"
    );
  }
}

export const performanceService = {
  runCheck: async (
    websiteId: string,
    userId: string,
    strategy: PerformanceStrategy,
    rawPageUrl?: string
  ) => {
    const website = await verifyOwnership(websiteId, userId);
    const pageUrl = resolveRequestedPageUrl(rawPageUrl, website.url);
    // Fetched BEFORE the PSI call/create below, deliberately -- this is the
    // one true same-(page+strategy) predecessor precisely because the new
    // row does not exist yet at the moment of this read, making self-
    // comparison structurally impossible (mirrors Stage 15.2's SEO
    // approach exactly). findLatestByWebsiteId is already pageUrl+strategy
    // scoped, so a MOBILE check can never be compared against a DESKTOP
    // predecessor, and a /services/ check can never be compared against
    // the homepage's own history, or vice versa (Stage P1 §18/§21).
    const previousCheck = await performanceRepository.findLatestByWebsiteId(websiteId, pageUrl, strategy);
    const result = await runPageSpeedCheck(pageUrl, strategy);
    const created = await performanceRepository.create(websiteId, pageUrl, strategy, result);
    await persistPerformanceAlert(websiteId, website.userId, pageUrl, strategy, previousCheck, created);
    return created;
  },
  // Scheduler-only entry point: no userId/ownership check because there is
  // no authenticated user in a background cycle — `website` is trusted as-is
  // since the caller (the performance worker) already fetched it directly
  // via performanceRepository.findActiveWebsites(), not from user input.
  // Shares the exact same PSI call + persistence as runCheck above, so
  // manual and automatic checks always produce identical PerformanceCheck
  // rows — only the ownership-verification step differs, appropriately.
  // Also shares the exact same persistPerformanceAlert call, so Alert
  // generation is identical for both paths.
  //
  // Stage P1 §16/§17: ALWAYS the website's own homepage (safeCanonicalize,
  // never resolveRequestedPageUrl/full validation -- see pageUrl.ts's own
  // doc comment for why) -- automatic scheduling never enrolls a manually-
  // tested subpage, by construction, not by a runtime check.
  runAutomaticCheck: async (
    website: { id: string; url: string; userId: string },
    strategy: PerformanceStrategy
  ) => {
    const pageUrl = safeCanonicalize(website.url);
    const previousCheck = await performanceRepository.findLatestByWebsiteId(website.id, pageUrl, strategy);
    const result = await runPageSpeedCheck(pageUrl, strategy);
    const created = await performanceRepository.create(website.id, pageUrl, strategy, result);
    await persistPerformanceAlert(website.id, website.userId, pageUrl, strategy, previousCheck, created);
    // Stage 16.5: scheduler-only automatic AI trigger -- deliberately not
    // called from runCheck (manual Performance test) above.
    await maybeRunAutomaticAiAnalysis(previousCheck, created);
    return created;
  },
  getLatest: async (
    websiteId: string,
    userId: string,
    strategy?: PerformanceStrategy,
    rawPageUrl?: string
  ) => {
    const website = await verifyOwnership(websiteId, userId);
    const pageUrl = resolveRequestedPageUrl(rawPageUrl, website.url);
    const check = await performanceRepository.findLatestByWebsiteId(websiteId, pageUrl, strategy);
    return { check, pageUrl };
  },
  // Chart-oriented history: strategy is mandatory (a chart must never mix
  // MOBILE/DESKTOP), bounded by MAX_HISTORY_RECORDS, and returned in
  // chronological (ascending) order for charting rather than the
  // DESC "most recent first" convention used elsewhere in this module.
  getHistory: async (
    websiteId: string,
    userId: string,
    strategy: PerformanceStrategy,
    range: PerformanceHistoryRange,
    rawPageUrl?: string
  ) => {
    const website = await verifyOwnership(websiteId, userId);
    const pageUrl = resolveRequestedPageUrl(rawPageUrl, website.url);
    const since = new Date(Date.now() - HISTORY_RANGE_MS[range]);

    const [checksDesc, total] = await Promise.all([
      performanceRepository.findHistoryByWebsiteIdStrategyAndRange(
        websiteId,
        pageUrl,
        strategy,
        since
      ),
      performanceRepository.countHistoryByWebsiteIdStrategyAndRange(
        websiteId,
        pageUrl,
        strategy,
        since
      ),
    ]);

    const checks = [...checksDesc].reverse().map((check) => ({
      ...check,
      // Reuses the same Stage 13.5 pure rating engine as /stats — no new
      // thresholds, just applied per historical record instead of only the
      // latest one, so the Recent Tests list can show a real backend rating
      // instead of inventing one client-side.
      ratings: ratePerformanceMetrics(check),
    }));

    return {
      strategy,
      range,
      pageUrl,
      checks,
      returned: checks.length,
      total,
      truncated: total > checks.length,
    };
  },
  getStats: async (
    websiteId: string,
    userId: string,
    strategy: PerformanceStrategy,
    rawPageUrl?: string
  ) => {
    const website = await verifyOwnership(websiteId, userId);
    const pageUrl = resolveRequestedPageUrl(rawPageUrl, website.url);
    const checks = await performanceRepository.findRecentByWebsiteIdAndStrategy(
      websiteId,
      pageUrl,
      strategy
    );
    const stats = computePerformanceStats(strategy, checks);
    // Ratings describe only the LATEST check, matching the rest of Sentinel
    // AI's real-time-status framing — averages/trend deltas are not rated.
    return { ...stats, pageUrl, ratings: ratePerformanceMetrics(stats.latest) };
  },
};
