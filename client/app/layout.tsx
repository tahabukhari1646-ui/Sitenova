import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import "./globals.css";
import { Providers } from "./providers";
import { THEME_INIT_SCRIPT } from "@/lib/theme";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

export default function RootLayout({ children }: LayoutProps<"/">) {
  return (
    <html
      lang="en"
      className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
      // Stage 16.9: the <head> script below sets the `.dark` class on this
      // element synchronously, BEFORE React hydrates -- suppressing only
      // the expected, intentional attribute mismatch this causes (never a
      // real bug), exactly like `suppressHydrationWarning` already does on
      // <body> below for the same class of reason.
      suppressHydrationWarning
    >
      <head>
        {/* Stage 16.9 §15: plain, dependency-free, self-authored script
            (not user/AI-authored content) -- applies the correct
            light/dark class before first paint to avoid a theme flash.
            See lib/theme.ts's THEME_INIT_SCRIPT doc comment. */}
        <script dangerouslySetInnerHTML={{ __html: THEME_INIT_SCRIPT }} />
      </head>
      <body className="min-h-full flex flex-col" suppressHydrationWarning>
        <Providers>{children}</Providers>
      </body>
    </html>
  );
}
